const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function F(n, brand, cat, k, sizes, diet = 'v', alias = '') {
  return { id: slug((brand ? brand + ' ' : '') + n), n, brand, cat, k, sizes, diet, alias, ml: cat === 'drinks' };
}
function U(n, brand, cat, unit, label, grams, price, diet = 'v', alias = '', extra = []) {
  const k = unit.map(v => Math.round((v / grams) * 1000) / 10);
  return F(n, brand, cat, k, [[label, grams, price], ...extra], diet, alias);
}

